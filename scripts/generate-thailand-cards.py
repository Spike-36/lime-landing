#!/usr/bin/env python3
"""Regenerate src/app/thailand/cards.ts from the YumWords Thailand export.

Reads the FileMaker-exported JSON bundled with the Flutter app
(data.json, collections.json, recipes/recipes.json) and writes the
"Beyond Pad Thai" (C002) cards in collection order. Text is copied
verbatim: nothing is rewritten, shortened or standardised.

Usage (from the repository root):
    python3 scripts/generate-thailand-cards.py [--source DIR] [--out FILE]

Defaults assume YumWords-v2 is checked out next to this repository.
Only the Python standard library is needed.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COLLECTION_ID = "C002"

parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
parser.add_argument("--source", type=Path, default=ROOT.parent / "YumWords-v2/assets/thailand",
                    help="YumWords-v2/assets/thailand directory")
parser.add_argument("--out", type=Path, default=ROOT / "src/app/thailand/cards.ts")
args = parser.parse_args()

src = args.source
data = {r["id"]: r for r in json.loads((src / "data.json").read_text())}
col = json.loads((src / "collections.json").read_text())
meta = next(c for c in col["collections"] if c["collectionId"] == COLLECTION_ID)
items = sorted(
    (i for i in col["collectionItems"] if i["collectionId"] == COLLECTION_ID),
    key=lambda i: i["sortOrder"],
)
recipes = json.loads((src / "recipes/recipes.json").read_text())
recipes = recipes if isinstance(recipes, list) else next(iter(recipes.values()))
recipe_ids = {r.get("featureCardId") for r in recipes}

cards = []
for it in items:
    r = data[it["blockId"]]
    cards.append({
        "id": r["id"],
        "name": r["english_short"],
        "thai": r["headword"],
        "phonetic": r["phonetic"],
        "description": r["description"],
        "goodToKnow": r.get("good_to_know") or [],
        "whereYouWillSeeIt": r.get("where_you_will_see_it") or [],
        "whenItsEaten": r.get("when_its_eaten") or [],
        "howPeopleUsuallyEatIt": r.get("how_people_usually_eat_it") or [],
        "firstImpressions": r.get("first_impressions") or [],
        "spiceLevel": r.get("infoSpiceLevel") or [],
        "ingredients": r.get("ingredients") or [],
        "preparation": r.get("preparation") or "",
        "hasRecipe": r["id"] in recipe_ids,
    })

head = '''// Generated by scripts/generate-thailand-cards.py from
// YumWords-v2/assets/thailand (data.json, collections.json,
// recipes/recipes.json): collection C002 "Beyond Pad Thai".
// Text is copied verbatim; media lives in public/media/thailand/.
// Do not edit by hand: change the source data and regenerate.

export type ThaiCard = {
  id: string
  name: string
  thai: string
  phonetic: string
  description: string
  goodToKnow: string[]
  whereYouWillSeeIt: string[]
  whenItsEaten: string[]
  howPeopleUsuallyEatIt: string[]
  firstImpressions: string[]
  spiceLevel: string[]
  ingredients: string[]
  // Paragraphs separated by blank lines, as in the export
  preparation: string
  hasRecipe: boolean
}

'''
collection = {"id": meta["collectionId"], "title": meta["title"], "subtitle": meta["subtitle"]}
body = "export const collection = " + json.dumps(collection, indent=2, ensure_ascii=False) + "\n\n"
body += "export const cards: ThaiCard[] = " + json.dumps(cards, indent=2, ensure_ascii=False) + "\n"
args.out.write_text(head + body)
print(f"Wrote {len(cards)} cards to {args.out}: {', '.join(c['id'] for c in cards)}")
